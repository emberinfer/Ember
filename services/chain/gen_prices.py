#!/usr/bin/env python3
"""Generate the price-derived genesis constants from the price table.

Single source of truth: genesis_prices.json (next to this script).
Output: genesis_prices_gen.go (same directory), consumed by
genesis_subsidy.go. The equivalents-to-subunits conversion is the fee of
one reference standard request under the reference class price, using
the chain fee formula (core-go/fees.go TokenFee):

    fee = price_input * n_in + price_output * n_out
          + floor(price_context * n_in * n_out / 1024)

Usage:
    python3 gen_prices.py           # regenerate genesis_prices_gen.go
    python3 gen_prices.py --check   # exit 1 if the generated file drifts
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TABLE = os.path.join(HERE, "genesis_prices.json")
OUT = os.path.join(HERE, "genesis_prices_gen.go")
CONTEXT_DIVISOR = 1024


def load_table():
    with open(TABLE) as f:
        table = json.load(f)
    ref = table["reference"]
    rows = {c["class"]: c for c in table["classes"]}
    if ref["class"] not in rows:
        raise SystemExit(f"reference class {ref['class']!r} not in classes")
    for name, row in rows.items():
        for k in ("price_input", "price_output", "price_context"):
            v = row[k]
            if not isinstance(v, int) or v < 0:
                raise SystemExit(f"class {name}: {k} must be a non-negative int")
    row = rows[ref["class"]]
    if row["price_output"] < 1:
        raise SystemExit("reference class price_output must be >= 1")
    return table, row


def reference_fee(table, row):
    n_in = int(table["reference"]["input_tokens"])
    n_out = int(table["reference"]["output_tokens"])
    fee = (
        row["price_input"] * n_in
        + row["price_output"] * n_out
        + row["price_context"] * n_in * n_out // CONTEXT_DIVISOR
    )
    return n_in, n_out, fee


def render(table, row):
    n_in, n_out, fee = reference_fee(table, row)
    return f"""package chain

// Code generated by gen_prices.py from genesis_prices.json. DO NOT EDIT.
//
// Genesis price calibration 2026-11-15: the equivalents-to-subunits
// conversion is the fee of one reference standard request
// ({n_in} input / {n_out} output tokens) under the reference class
// ({table["reference"]["class"]}) price, via the chain fee formula.
// Every price-derived Spark face-value constant in the subsidy system
// flows from this value; the equivalents and BPS constants in
// genesis_subsidy.go are price-independent and stay hand-written there.
const (
\tGenesisReferencePriceInput   int64 = {row["price_input"]}
\tGenesisReferencePriceOutput  int64 = {row["price_output"]}
\tGenesisReferencePriceContext int64 = {row["price_context"]}

\tSubsidyReferenceInput     int64 = {n_in}
\tSubsidyReferenceOutput    int64 = {n_out}
\tSubsidyEquivalentSubunits int64 = {fee}
)
"""


def main():
    table, row = load_table()
    text = render(table, row)
    if "--check" in sys.argv:
        with open(OUT) as f:
            current = f.read()
        if current != text:
            print("genesis_prices_gen.go drifts from genesis_prices.json", file=sys.stderr)
            return 1
        print("genesis_prices_gen.go matches genesis_prices.json")
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    _, _, fee = reference_fee(table, row)
    print(f"wrote {OUT} (SubsidyEquivalentSubunits = {fee})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
